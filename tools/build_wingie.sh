#!/bin/sh
# Build Sleepcousonique for the Meng Qi Wingie2 (ESP32, Arduino core 2.0.4).
#   tools/build_wingie.sh            -> firmware-wingie/dist/sleepcousonique-wingie.bin (flash at 0x0)
# Needs: arduino-cli, esp32:esp32@2.0.4, the "Adafruit AW9523" library.
set -e
cd "$(dirname "$0")/.."
SK=firmware-wingie/SleepcousoniqueWingie
rm -rf "$SK/src"; mkdir -p "$SK/src/engine"
cp engine/*.c engine/*.h engine/*.inc "$SK/src/engine/"
python3 - <<'PY'
import json
t = open("examples/wingie-first-light.dream").read()
open("firmware-wingie/SleepcousoniqueWingie/first_light.h", "w").write(
    "// generated by tools/build_wingie.sh from examples/wingie-first-light.dream\n"
    "static const char FIRST_LIGHT[] = " + json.dumps(t) + ";\n")
PY
FLAGS="-O2 -DSCQ_DEVICE -DSCQ_INSTRUMENT=1 -DSCQ_POOL_EXTERN -I$(pwd)/engine"
mkdir -p build-wingie firmware-wingie/dist
arduino-cli compile --fqbn "esp32:esp32:esp32:PartitionScheme=default,FlashMode=dio,FlashFreq=80" \
  --build-property "compiler.c.extra_flags=$FLAGS" --build-property "compiler.cpp.extra_flags=$FLAGS" \
  --output-dir build-wingie "$SK" 2>&1 | grep -E "error|warning: |Sketch uses|Global variables" | grep -v "deprecated" || true
test -f build-wingie/SleepcousoniqueWingie.ino.bin
ESPTOOL=$(ls ~/Library/Arduino15/packages/esp32/tools/esptool_py/*/esptool | tail -1)
BOOT0=$(ls ~/Library/Arduino15/packages/esp32/hardware/esp32/2.0.4/tools/partitions/boot_app0.bin)
"$ESPTOOL" --chip esp32 merge_bin -o firmware-wingie/dist/sleepcousonique-wingie.bin \
  --flash_mode dio --flash_freq 80m --flash_size 4MB \
  0x1000 build-wingie/SleepcousoniqueWingie.ino.bootloader.bin 0x8000 build-wingie/SleepcousoniqueWingie.ino.partitions.bin \
  0xe000 "$BOOT0" 0x10000 build-wingie/SleepcousoniqueWingie.ino.bin >/dev/null
echo "-> firmware-wingie/dist/sleepcousonique-wingie.bin"
